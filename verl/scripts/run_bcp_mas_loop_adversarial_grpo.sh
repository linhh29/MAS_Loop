#!/usr/bin/env bash
set -xeuo pipefail

# Disable core dumps: large vLLM/Ray crashes must not fill /tmp with core files.
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true
# BrowseComp-Plus MAS-Loop adversarial GRPO launcher.
# Only uses this repository's ./verl code. All local vLLM services use GPUs 8-15
# together with tensor-parallel=8 and vLLM sleep mode; the active model is woken
# on demand by mas_loop_rl.local_client.

MAS_ROOT=${MAS_ROOT:-/path/to/MAS_Loop}
VERL_ROOT=${VERL_ROOT:-${MAS_ROOT}/verl}
export VLLM_SERVER_DEV_MODE=${VLLM_SERVER_DEV_MODE:-1}
export VLLM_USE_V1=${VLLM_USE_V1:-1}
export PYTHONPATH="${MAS_LOOP_RUNTIME_DEPS_DIR:-${VERL_ROOT}/.mas_loop_runtime_deps}:${VERL_ROOT}:${MAS_ROOT}:${PYTHONPATH:-}"

export ALL_GPUS=${ALL_GPUS:-8,9,10,11,12,13,14,15}
TASK_JSONL=${TASK_JSONL:-${MAS_ROOT}/datasets/BrowseComp-Plus/data/browsecomp_plus_train.jsonl}
RUN_DIR=${RUN_DIR:-/path/to/checkpoints/benchmarks/mas_loop_grpo_bcp}
DATA_DIR=${DATA_DIR:-${RUN_DIR}/data}
LOG_DIR=${LOG_DIR:-${RUN_DIR}/logs}
mkdir -p "${DATA_DIR}" "${LOG_DIR}"

# Real BrowseComp-Plus BM25 retrieval over the local downloaded corpus/index.
export MAS_LOOP_RETRIEVER=${MAS_LOOP_RETRIEVER:-bm25}
export MAS_LOOP_BCP_ROOT=${MAS_LOOP_BCP_ROOT:-${MAS_ROOT}/datasets/BrowseComp-Plus}
export MAS_LOOP_BM25_INDEX=${MAS_LOOP_BM25_INDEX:-${MAS_LOOP_BCP_ROOT}/scripts_build_index/indexes/bm25}
export MAS_LOOP_BM25_TOPK=${MAS_LOOP_BM25_TOPK:-5}
export MAS_LOOP_BM25_DOC_MAX_CHARS=${MAS_LOOP_BM25_DOC_MAX_CHARS:-1200}
# Every BCP sub-agent independently performs five fresh LLM-planned BM25 turns.
# Query/result caching is process-memory-only; no persistent BM25 cache is written.
export MAS_LOOP_BCP_SEARCH_ROUNDS=${MAS_LOOP_BCP_SEARCH_ROUNDS:-5}
export MAS_LOOP_BCP_SEARCH_PLANNER_MAX_TOKENS=${MAS_LOOP_BCP_SEARCH_PLANNER_MAX_TOKENS:-256}
export MAS_LOOP_BCP_SEARCH_PLANNER_TEMPERATURE=${MAS_LOOP_BCP_SEARCH_PLANNER_TEMPERATURE:-0.4}
export MAS_LOOP_BCP_SEARCH_DIGEST_CHARS=${MAS_LOOP_BCP_SEARCH_DIGEST_CHARS:-10000}
export MAS_LOOP_BCP_SEARCH_CONTEXT_CHARS=${MAS_LOOP_BCP_SEARCH_CONTEXT_CHARS:-5000}
export MAS_LOOP_BCP_FINAL_MAX_DOCS=${MAS_LOOP_BCP_FINAL_MAX_DOCS:-15}
export MAS_LOOP_BCP_FINAL_MAX_CHARS=${MAS_LOOP_BCP_FINAL_MAX_CHARS:-18000}

# Smoke/debug can set MAX_TRAIN_ROWS=8. Full BCP training keeps 0 (=all rows).
MAX_TRAIN_ROWS=${MAX_TRAIN_ROWS:-0}
MAS_LOOP_DATASET_NAME=${MAS_LOOP_DATASET_NAME:-bcp}

# Local model default: keep every MAS-Loop role on /tmp-hosted checkpoints/models.
MODEL_PATH=${MODEL_PATH:-/path/to/models/Qwen3-8B}
SUBAGENT_MODEL=${SUBAGENT_MODEL:-/path/to/models/Qwen3-30B-A3B}
TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-64}
# The paper/table mini-batch is 256, but vanilla Verl requires ppo_mini_batch_size <= train_batch_size.
PPO_MINI_BATCH_SIZE=${PPO_MINI_BATCH_SIZE:-64}
PPO_MICRO_BATCH_SIZE_PER_GPU=${PPO_MICRO_BATCH_SIZE_PER_GPU:-2}
LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-4}
ROLLOUT_N=${ROLLOUT_N:-8}
export MAS_LOOP_EDITOR_CANDIDATES_PER_SOURCE=${MAS_LOOP_EDITOR_CANDIDATES_PER_SOURCE:-8}
EDITOR_GROUP_SIZE=${EDITOR_GROUP_SIZE:-${MAS_LOOP_EDITOR_CANDIDATES_PER_SOURCE}}
TOTAL_EPOCHS=${TOTAL_EPOCHS:-1}
ACTOR_TEMPERATURE=${ACTOR_TEMPERATURE:-0.7}
export MAS_LOOP_EDITOR_TEMPERATURE=${MAS_LOOP_EDITOR_TEMPERATURE:-0.7}
export MAS_LOOP_ACCEPT_REGRET_WEIGHT=${MAS_LOOP_ACCEPT_REGRET_WEIGHT:-0.0}
MAX_PROMPT_LENGTH=${MAX_PROMPT_LENGTH:-15000}
MAX_RESPONSE_LENGTH=${MAX_RESPONSE_LENGTH:-8192}
ADVERSARIAL_ROUNDS=${ADVERSARIAL_ROUNDS:-1}
VAL_BEFORE_TRAIN=${VAL_BEFORE_TRAIN:-False}
TEST_FREQ=${TEST_FREQ:--1}
# Save every 250 optimizer steps and always save the final step. Completed
# HuggingFace checkpoints are atomically published under MAS_LOOP_CKPT_ROOT.
NUM_INTERMEDIATE_CHECKPOINTS=${NUM_INTERMEDIATE_CHECKPOINTS:-0}
SAVE_FREQ=${SAVE_FREQ:-250}
ROLLOUT_ENABLE_SLEEP_MODE=${ROLLOUT_ENABLE_SLEEP_MODE:-1}
DATA_PREP_SEED=${DATA_PREP_SEED:-0}
DATA_VAL_RATIO=${DATA_VAL_RATIO:-0}
DATA_PAD_TO_MULTIPLE=${DATA_PAD_TO_MULTIPLE:-${TRAIN_BATCH_SIZE}}
export MAS_LOOP_MAX_CONCURRENCY=${MAS_LOOP_MAX_CONCURRENCY:-128}
# BCP owns this value independently from DeepScaleR. It limits outstanding Ray
# generate RPCs, not vLLM scheduler/KV capacity.
BCP_RAY_GENERATE_MAX_OUTSTANDING=${BCP_RAY_GENERATE_MAX_OUTSTANDING:-128}

# Reliability defaults matching the DeepScaleR launcher: all vLLM engines span
# GPUs 8-15, sleep when idle, and run eager to avoid V1 CUDA-graph recapture
# stalls observed in the previous BCP full run.
export ROLLOUT_GPU_MEM_UTIL=${ROLLOUT_GPU_MEM_UTIL:-0.90}
export EXTERNAL_VLLM_GPU_MEM_UTIL=${EXTERNAL_VLLM_GPU_MEM_UTIL:-0.82}
export PEER_GPU_MEMORY_UTILIZATION=${PEER_GPU_MEMORY_UTILIZATION:-${EXTERNAL_VLLM_GPU_MEM_UTIL}}
export SUB_AGENT_GPU_MEMORY_UTILIZATION=${SUB_AGENT_GPU_MEMORY_UTILIZATION:-${EXTERNAL_VLLM_GPU_MEM_UTIL}}
# Keep the three vLLM schedulers explicit in the BCP namespace so tuning this
# launcher cannot silently fall back to generic-script defaults.
export VLLM_MAX_NUM_SEQS=${VLLM_MAX_NUM_SEQS:-128}
export ROLLOUT_MAX_NUM_SEQS=${ROLLOUT_MAX_NUM_SEQS:-${VLLM_MAX_NUM_SEQS}}
export PEER_MAX_NUM_SEQS=${PEER_MAX_NUM_SEQS:-${VLLM_MAX_NUM_SEQS}}
export SUB_AGENT_MAX_NUM_SEQS=${SUB_AGENT_MAX_NUM_SEQS:-${VLLM_MAX_NUM_SEQS}}
export ROLLOUT_MAX_NUM_BATCHED_TOKENS=${ROLLOUT_MAX_NUM_BATCHED_TOKENS:-32768}
export PEER_MAX_NUM_BATCHED_TOKENS=${PEER_MAX_NUM_BATCHED_TOKENS:-32768}
export SUB_AGENT_MAX_NUM_BATCHED_TOKENS=${SUB_AGENT_MAX_NUM_BATCHED_TOKENS:-32768}
export ROLLOUT_MAX_NUM_PARTIAL_PREFILLS=${ROLLOUT_MAX_NUM_PARTIAL_PREFILLS:-1}
export ROLLOUT_MAX_LONG_PARTIAL_PREFILLS=${ROLLOUT_MAX_LONG_PARTIAL_PREFILLS:-1}
export PEER_MAX_NUM_PARTIAL_PREFILLS=${PEER_MAX_NUM_PARTIAL_PREFILLS:-1}
export PEER_MAX_LONG_PARTIAL_PREFILLS=${PEER_MAX_LONG_PARTIAL_PREFILLS:-1}
export SUB_AGENT_MAX_NUM_PARTIAL_PREFILLS=${SUB_AGENT_MAX_NUM_PARTIAL_PREFILLS:-1}
export SUB_AGENT_MAX_LONG_PARTIAL_PREFILLS=${SUB_AGENT_MAX_LONG_PARTIAL_PREFILLS:-1}
export MAS_LOOP_DISPATCH_WORKERS_PER_PROCESS=${MAS_LOOP_DISPATCH_WORKERS_PER_PROCESS:-128}
export SUB_AGENT_MAX_MODEL_LEN=${SUB_AGENT_MAX_MODEL_LEN:-8192}
export ROLLOUT_ENFORCE_EAGER=${ROLLOUT_ENFORCE_EAGER:-1}
export EXTERNAL_VLLM_ENFORCE_EAGER=${EXTERNAL_VLLM_ENFORCE_EAGER:-1}
export RAY_DASHBOARD_PORT=${RAY_DASHBOARD_PORT:-8315}
export RAY_TEMP_DIR=${RAY_TEMP_DIR:-/tmp/mas_loop_ray_bcp}
export MAS_LOOP_PAIR_DIR=${MAS_LOOP_PAIR_DIR:-${LOG_DIR}/pairs}

python3 -m mas_loop_rl.prepare_data \
  --input "${TASK_JSONL}" \
  --output-dir "${DATA_DIR}" \
  --role both \
  --seed "${DATA_PREP_SEED}" \
  --val-ratio "${DATA_VAL_RATIO}" \
  --max-rows "${MAX_TRAIN_ROWS}" --pad-train-to-multiple "${DATA_PAD_TO_MULTIPLE}"

# Delegate the alternating adversarial GRPO phases to the generic MAS-Loop script.
MAS_ROOT="${MAS_ROOT}" VERL_ROOT="${VERL_ROOT}" ALL_GPUS="${ALL_GPUS}" \
TASK_JSONL="${TASK_JSONL}" RUN_DIR="${RUN_DIR}" DATA_DIR="${DATA_DIR}" LOG_DIR="${LOG_DIR}" \
MODEL_PATH="${MODEL_PATH}" ORCHESTRA_MODEL="${MODEL_PATH}" EDITOR_MODEL="${MODEL_PATH}" SUBAGENT_MODEL="${SUBAGENT_MODEL}" TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE}" PPO_MINI_BATCH_SIZE="${PPO_MINI_BATCH_SIZE}" \
ROLLOUT_N="${ROLLOUT_N}" MAS_LOOP_EDITOR_CANDIDATES_PER_SOURCE="${MAS_LOOP_EDITOR_CANDIDATES_PER_SOURCE}" EDITOR_GROUP_SIZE="${EDITOR_GROUP_SIZE}" ACTOR_TEMPERATURE="${ACTOR_TEMPERATURE}" MAS_LOOP_EDITOR_TEMPERATURE="${MAS_LOOP_EDITOR_TEMPERATURE}" MAS_LOOP_ACCEPT_REGRET_WEIGHT="${MAS_LOOP_ACCEPT_REGRET_WEIGHT}" PPO_MICRO_BATCH_SIZE_PER_GPU="${PPO_MICRO_BATCH_SIZE_PER_GPU}" LOG_PROB_MICRO_BATCH_SIZE_PER_GPU="${LOG_PROB_MICRO_BATCH_SIZE_PER_GPU}" TOTAL_EPOCHS="${TOTAL_EPOCHS}" MAX_PROMPT_LENGTH="${MAX_PROMPT_LENGTH}" \
MAX_RESPONSE_LENGTH="${MAX_RESPONSE_LENGTH}" ADVERSARIAL_ROUNDS="${ADVERSARIAL_ROUNDS}" VAL_BEFORE_TRAIN="${VAL_BEFORE_TRAIN}" DATA_PREP_SEED="${DATA_PREP_SEED}" DATA_VAL_RATIO="${DATA_VAL_RATIO}" DATA_PAD_TO_MULTIPLE="${DATA_PAD_TO_MULTIPLE}" MAS_LOOP_MAX_CONCURRENCY="${MAS_LOOP_MAX_CONCURRENCY}" PEER_GPU_MEMORY_UTILIZATION="${PEER_GPU_MEMORY_UTILIZATION}" SUB_AGENT_GPU_MEMORY_UTILIZATION="${SUB_AGENT_GPU_MEMORY_UTILIZATION}" \
MAS_LOOP_RAY_GENERATE_MAX_OUTSTANDING="${BCP_RAY_GENERATE_MAX_OUTSTANDING}" \
ROLLOUT_MAX_NUM_SEQS="${ROLLOUT_MAX_NUM_SEQS}" PEER_MAX_NUM_SEQS="${PEER_MAX_NUM_SEQS}" SUB_AGENT_MAX_NUM_SEQS="${SUB_AGENT_MAX_NUM_SEQS}" \
ROLLOUT_MAX_NUM_BATCHED_TOKENS="${ROLLOUT_MAX_NUM_BATCHED_TOKENS}" PEER_MAX_NUM_BATCHED_TOKENS="${PEER_MAX_NUM_BATCHED_TOKENS}" SUB_AGENT_MAX_NUM_BATCHED_TOKENS="${SUB_AGENT_MAX_NUM_BATCHED_TOKENS}" \
ROLLOUT_MAX_NUM_PARTIAL_PREFILLS="${ROLLOUT_MAX_NUM_PARTIAL_PREFILLS}" ROLLOUT_MAX_LONG_PARTIAL_PREFILLS="${ROLLOUT_MAX_LONG_PARTIAL_PREFILLS}" \
PEER_MAX_NUM_PARTIAL_PREFILLS="${PEER_MAX_NUM_PARTIAL_PREFILLS}" PEER_MAX_LONG_PARTIAL_PREFILLS="${PEER_MAX_LONG_PARTIAL_PREFILLS}" \
SUB_AGENT_MAX_NUM_PARTIAL_PREFILLS="${SUB_AGENT_MAX_NUM_PARTIAL_PREFILLS}" SUB_AGENT_MAX_LONG_PARTIAL_PREFILLS="${SUB_AGENT_MAX_LONG_PARTIAL_PREFILLS}" \
MAS_LOOP_DISPATCH_WORKERS_PER_PROCESS="${MAS_LOOP_DISPATCH_WORKERS_PER_PROCESS}" SUB_AGENT_MAX_MODEL_LEN="${SUB_AGENT_MAX_MODEL_LEN}" \
"${VERL_ROOT}/scripts/run_mas_loop_adversarial_grpo.sh" "$@"
