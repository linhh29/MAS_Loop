#!/usr/bin/env bash
set -euo pipefail
# Benchmarks inherit this limit into Ray and every local vLLM worker.
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

ROOT=/path/to/MAS_Loop
[[ "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" == "${ROOT}" ]] || {
  echo "Refusing to run outside ${ROOT}" >&2; exit 2;
}

BATCH=${1:-144}
[[ "${BATCH}" =~ ^[0-9]+$ ]] && (( BATCH > 0 && BATCH % 8 == 0 )) || {
  echo "batch must be a positive multiple of 8" >&2; exit 2;
}
ROLLOUT_N=${BENCH_ROLLOUT_N:-8}
NUM_STEPS=${BENCH_NUM_STEPS:-1}
RUN_EDITOR=${BENCH_RUN_EDITOR:-0}
EDITOR_TRAIN_BATCH_SIZE=${BENCH_EDITOR_TRAIN_BATCH_SIZE:-$((BATCH * ROLLOUT_N))}
(( NUM_STEPS > 0 )) || { echo "BENCH_NUM_STEPS must be positive" >&2; exit 2; }
EXPECTED_SAMPLES=$((BATCH * NUM_STEPS))
TRAJECTORIES=$((BATCH * ROLLOUT_N))
ROLLOUT_SEQS=${BENCH_ROLLOUT_MAX_NUM_SEQS:-128}
PEER_SEQS=${BENCH_PEER_MAX_NUM_SEQS:-128}
SUB_SEQS=${BENCH_SUB_AGENT_MAX_NUM_SEQS:-128}
MAX_CONCURRENCY=${BENCH_MAX_CONCURRENCY:-128}
DISPATCH_WORKERS=${BENCH_DISPATCH_WORKERS:-128}
PPO_MINI=${BENCH_PPO_MINI_BATCH_SIZE:-128}
PPO_MICRO=${BENCH_PPO_MICRO_BATCH_SIZE_PER_GPU:-2}
LOG_PROB_MICRO=${BENCH_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-4}
COMMON_BATCHED_TOKENS=${BENCH_MAX_NUM_BATCHED_TOKENS:-32768}
ROLLOUT_BATCHED_TOKENS=${BENCH_ROLLOUT_MAX_NUM_BATCHED_TOKENS:-${COMMON_BATCHED_TOKENS}}
PEER_BATCHED_TOKENS=${BENCH_PEER_MAX_NUM_BATCHED_TOKENS:-${COMMON_BATCHED_TOKENS}}
SUB_BATCHED_TOKENS=${BENCH_SUB_AGENT_MAX_NUM_BATCHED_TOKENS:-${COMMON_BATCHED_TOKENS}}
ROLLOUT_GPU_MEM_UTIL=${BENCH_ROLLOUT_GPU_MEM_UTIL:-0.85}
PEER_GPU_MEM_UTIL=${BENCH_PEER_GPU_MEMORY_UTILIZATION:-0.90}
SUB_GPU_MEM_UTIL=${BENCH_SUB_AGENT_GPU_MEMORY_UTILIZATION:-0.90}
VLLM_MAX_ACTIVE=${BENCH_VLLM_MAX_ACTIVE:-${MAX_CONCURRENCY}}
ORCHESTRA_VLLM_MAX_ACTIVE=${BENCH_ORCHESTRA_VLLM_MAX_ACTIVE:-${VLLM_MAX_ACTIVE}}
EDITOR_VLLM_MAX_ACTIVE=${BENCH_EDITOR_VLLM_MAX_ACTIVE:-${VLLM_MAX_ACTIVE}}
SUB_AGENT_VLLM_MAX_ACTIVE=${BENCH_SUB_AGENT_VLLM_MAX_ACTIVE:-${VLLM_MAX_ACTIVE}}
RAY_SERVER_MAX_CONCURRENCY=${BENCH_RAY_SERVER_MAX_CONCURRENCY:-128}
RAY_GENERATE_MAX_OUTSTANDING=${BENCH_RAY_GENERATE_MAX_OUTSTANDING:-128}
TS=${DS_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
SESSION=${DS_SESSION:-masloop_ds_b${BATCH}_${TS}}
RUN_ROOT=${DS_RUN_ROOT:-/path/to/checkpoints/benchmarks/deepscaler_concurrency_b${BATCH}_orch${ROLLOUT_SEQS}_editor${PEER_SEQS}_sub${SUB_SEQS}_c${MAX_CONCURRENCY}_tok${ROLLOUT_BATCHED_TOKENS}-${PEER_BATCHED_TOKENS}-${SUB_BATCHED_TOKENS}_1step_${TS}}
STATUS_LOG=${DS_STATUS_LOG:-/tmp/${SESSION}.status.log}
LOG=${DS_LAUNCH_LOG:-${RUN_ROOT}/trial_launcher.log}

mkdir -p "${RUN_ROOT}" "/path/to/checkpoints"
JOB_ENV_TMP="/path/to/checkpoints/benchmarks/current_mas_loop_job.env.tmp.$$"
cat > "${JOB_ENV_TMP}" <<EOF
RUN_DIR=${RUN_ROOT}/train
RUN_NAME=$(basename "${RUN_ROOT}")
GPU_SET=8,9,10,11,12,13,14,15
LAUNCH_SCRIPT=${ROOT}/verl/scripts/run_deepscaler_vllm_concurrency_trial.sh
START_TIME=$(date +%s)
SESSION=${SESSION}
DATASET=deepscaler
EXPECTED_SAMPLES=${EXPECTED_SAMPLES}
PAIR_GROUP_SIZE=${ROLLOUT_N}
MODE=concurrency_trial
NUM_STEPS=${NUM_STEPS}
WAIT_LOG=${STATUS_LOG}
EOF
mv -f "${JOB_ENV_TMP}" "/path/to/checkpoints/benchmarks/current_mas_loop_job.env"

printf '[trial] batch=%s trajectories=%s orchestra=%s editor=%s sub_agent=%s dispatch_concurrency=%s active(o/e/s)=%s/%s/%s workers=%s batched_tokens=%s/%s/%s gpu_util=%s/%s/%s\n' \
  "${BATCH}" "${TRAJECTORIES}" "${ROLLOUT_SEQS}" "${PEER_SEQS}" "${SUB_SEQS}" "${MAX_CONCURRENCY}" "${ORCHESTRA_VLLM_MAX_ACTIVE}" "${EDITOR_VLLM_MAX_ACTIVE}" "${SUB_AGENT_VLLM_MAX_ACTIVE}" "${DISPATCH_WORKERS}" \
  "${ROLLOUT_BATCHED_TOKENS}" "${PEER_BATCHED_TOKENS}" "${SUB_BATCHED_TOKENS}" "${ROLLOUT_GPU_MEM_UTIL}" "${PEER_GPU_MEM_UTIL}" "${SUB_GPU_MEM_UTIL}"
printf '[trial] ray_server_max_concurrency=%s ray_generate_max_outstanding=%s\n' \
  "${RAY_SERVER_MAX_CONCURRENCY}" "${RAY_GENERATE_MAX_OUTSTANDING}"
printf '[trial] waiting for exclusive access to GPU 8-15; foreign sleep-mode processes also block launch\n'
PYTHONPATH="${ROOT}/verl" python3 -m mas_loop_rl.wait_for_gpu_isolation \
  --gpus 8,9,10,11,12,13,14,15 \
  --interval "${GPU_ISOLATION_CHECK_INTERVAL:-60}" \
  --stable-checks "${GPU_ISOLATION_STABLE_CHECKS:-2}"

mkdir -p "${RUN_ROOT}"
cat > "${RUN_ROOT}/trial_config.env" <<EOF
BATCH=${BATCH}
NUM_STEPS=${NUM_STEPS}
RUN_EDITOR=${RUN_EDITOR}
EDITOR_TRAIN_BATCH_SIZE=${EDITOR_TRAIN_BATCH_SIZE}
EXPECTED_SAMPLES=${EXPECTED_SAMPLES}
ROLLOUT_N=${ROLLOUT_N}
TRAJECTORIES=${TRAJECTORIES}
ROLLOUT_SEQS=${ROLLOUT_SEQS}
PEER_SEQS=${PEER_SEQS}
SUB_SEQS=${SUB_SEQS}
MAX_CONCURRENCY=${MAX_CONCURRENCY}
VLLM_MAX_ACTIVE=${VLLM_MAX_ACTIVE}
ORCHESTRA_VLLM_MAX_ACTIVE=${ORCHESTRA_VLLM_MAX_ACTIVE}
EDITOR_VLLM_MAX_ACTIVE=${EDITOR_VLLM_MAX_ACTIVE}
SUB_AGENT_VLLM_MAX_ACTIVE=${SUB_AGENT_VLLM_MAX_ACTIVE}
RAY_SERVER_MAX_CONCURRENCY=${RAY_SERVER_MAX_CONCURRENCY}
RAY_GENERATE_MAX_OUTSTANDING=${RAY_GENERATE_MAX_OUTSTANDING}
ROLLOUT_GPU_MEM_UTIL=${ROLLOUT_GPU_MEM_UTIL}
PEER_GPU_MEMORY_UTILIZATION=${PEER_GPU_MEM_UTIL}
SUB_AGENT_GPU_MEMORY_UTILIZATION=${SUB_GPU_MEM_UTIL}
DISPATCH_WORKERS=${DISPATCH_WORKERS}
PPO_MINI=${PPO_MINI}
PPO_MICRO_BATCH_SIZE_PER_GPU=${PPO_MICRO}
LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${LOG_PROB_MICRO}
ROLLOUT_MAX_NUM_BATCHED_TOKENS=${ROLLOUT_BATCHED_TOKENS}
PEER_MAX_NUM_BATCHED_TOKENS=${PEER_BATCHED_TOKENS}
SUB_AGENT_MAX_NUM_BATCHED_TOKENS=${SUB_BATCHED_TOKENS}
HTTP_TRANSPORT=${BENCH_HTTP_TRANSPORT:-urllib3}
VLLM_HTTP_BACKLOG=${BENCH_VLLM_HTTP_BACKLOG:-16384}
VLLM_HTTP_TIMEOUT_KEEP_ALIVE=${BENCH_VLLM_HTTP_TIMEOUT_KEEP_ALIVE:-60}
ACTOR_GUIDED_JSON=${BENCH_ACTOR_GUIDED_JSON:-0}
EDITOR_AGENT_OUTPUT_CHARS=${BENCH_EDITOR_AGENT_OUTPUT_CHARS:-2400}
EDITOR_AGENT_ERROR_CHARS=${BENCH_EDITOR_AGENT_ERROR_CHARS:-800}
EDITOR_FINAL_OUTPUT_CHARS=${BENCH_EDITOR_FINAL_OUTPUT_CHARS:-4000}
ORCHESTRA_HTTP_POOL_MAXSIZE=${BENCH_ORCHESTRA_HTTP_POOL_MAXSIZE:-128}
EDITOR_HTTP_POOL_MAXSIZE=${BENCH_EDITOR_HTTP_POOL_MAXSIZE:-128}
SUBAGENT_HTTP_POOL_MAXSIZE=${BENCH_SUBAGENT_HTTP_POOL_MAXSIZE:-128}
TQ_DATA_UPDATE_MAX_CONCURRENCY=${BENCH_TQ_DATA_UPDATE_MAX_CONCURRENCY:-128}
TQ_DATA_UPDATE_MAX_RETRIES=${BENCH_TQ_DATA_UPDATE_MAX_RETRIES:-3}
TQ_DATA_UPDATE_RETRY_BACKOFF_SEC=${BENCH_TQ_DATA_UPDATE_RETRY_BACKOFF_SEC:-0.25}
SESSION=${SESSION}
RUN_ROOT=${RUN_ROOT}
EOF

set +e
env \
  DS_TIMESTAMP="${TS}" DS_SESSION="${SESSION}" DS_RUN_ROOT="${RUN_ROOT}" \
  BENCH_NUM_STEPS="${NUM_STEPS}" BENCH_RUN_EDITOR="${RUN_EDITOR}" BENCH_EDITOR_TRAIN_BATCH_SIZE="${EDITOR_TRAIN_BATCH_SIZE}" \
  BENCH_TRAIN_BATCH_SIZE="${BATCH}" BENCH_PPO_MINI_BATCH_SIZE="${PPO_MINI}" \
  BENCH_PPO_MICRO_BATCH_SIZE_PER_GPU="${PPO_MICRO}" BENCH_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU="${LOG_PROB_MICRO}" \
  BENCH_ROLLOUT_MAX_NUM_SEQS="${ROLLOUT_SEQS}" BENCH_PEER_MAX_NUM_SEQS="${PEER_SEQS}" \
  BENCH_SUB_AGENT_MAX_NUM_SEQS="${SUB_SEQS}" BENCH_MAX_CONCURRENCY="${MAX_CONCURRENCY}" \
  BENCH_DISPATCH_WORKERS="${DISPATCH_WORKERS}" \
  BENCH_ROLLOUT_MAX_NUM_BATCHED_TOKENS="${ROLLOUT_BATCHED_TOKENS}" \
  BENCH_PEER_MAX_NUM_BATCHED_TOKENS="${PEER_BATCHED_TOKENS}" \
  BENCH_SUB_AGENT_MAX_NUM_BATCHED_TOKENS="${SUB_BATCHED_TOKENS}" \
  BENCH_ROLLOUT_GPU_MEM_UTIL="${ROLLOUT_GPU_MEM_UTIL}" \
  BENCH_PEER_GPU_MEMORY_UTILIZATION="${PEER_GPU_MEM_UTIL}" \
  BENCH_SUB_AGENT_GPU_MEMORY_UTILIZATION="${SUB_GPU_MEM_UTIL}" \
  BENCH_VLLM_MAX_ACTIVE="${VLLM_MAX_ACTIVE}" \
  BENCH_ORCHESTRA_VLLM_MAX_ACTIVE="${ORCHESTRA_VLLM_MAX_ACTIVE}" \
  BENCH_EDITOR_VLLM_MAX_ACTIVE="${EDITOR_VLLM_MAX_ACTIVE}" \
  BENCH_SUB_AGENT_VLLM_MAX_ACTIVE="${SUB_AGENT_VLLM_MAX_ACTIVE}" \
  BENCH_RAY_SERVER_MAX_CONCURRENCY="${RAY_SERVER_MAX_CONCURRENCY}" \
  BENCH_RAY_GENERATE_MAX_OUTSTANDING="${RAY_GENERATE_MAX_OUTSTANDING}" \
  BENCH_TQ_DATA_UPDATE_MAX_CONCURRENCY="${BENCH_TQ_DATA_UPDATE_MAX_CONCURRENCY:-128}" \
  BENCH_TQ_DATA_UPDATE_MAX_RETRIES="${BENCH_TQ_DATA_UPDATE_MAX_RETRIES:-3}" \
  BENCH_TQ_DATA_UPDATE_RETRY_BACKOFF_SEC="${BENCH_TQ_DATA_UPDATE_RETRY_BACKOFF_SEC:-0.25}" \
  bash "${ROOT}/verl/scripts/run_deepscaler_vllm_concurrency_1step.sh" \
  >"${LOG}" 2>&1 &
TRAIN_PID=$!
PYTHONPATH="${ROOT}/verl" python3 -m mas_loop_rl.monitor_vllm_metrics \
  --launcher-log "${LOG}" \
  --output "${RUN_ROOT}/train/logs/orchestra_vllm_metrics.log" \
  --pid "${TRAIN_PID}" --interval "${ORCHESTRA_METRICS_INTERVAL:-2}" &
MONITOR_PID=$!
RUNTIME_MONITOR_PID=
if [[ "${BENCH_RUNTIME_MONITOR:-1}" == "1" ]]; then
  MAS_LOOP_VLLM_CONTROL_SOCKET="${MAS_LOOP_VLLM_CONTROL_SOCKET:-/tmp/mas_loop_deepscaler_control_${TS}/coordinator.sock}" \
  PYTHONPATH="${ROOT}/verl" python3 -m mas_loop_rl.monitor_runtime_state \
    --output "${RUN_ROOT}/runtime_metrics.jsonl" --pid "${TRAIN_PID}" \
    --interval "${BENCH_RUNTIME_MONITOR_INTERVAL:-5}" --gpus 8,9,10,11,12,13,14,15 \
    --editor-url http://127.0.0.1:8111 --subagent-url http://127.0.0.1:8112 \
    --dispatch-dir "/tmp/mas_loop_deepscaler_control_${TS}/dispatch_metrics" \
    --ray-lb-dir "/tmp/mas_loop_deepscaler_control_${TS}/ray_lb_metrics" &
  RUNTIME_MONITOR_PID=$!
fi
wait "${TRAIN_PID}"
RC=$?
wait "${MONITOR_PID}" || true
if [[ -n "${RUNTIME_MONITOR_PID}" ]]; then wait "${RUNTIME_MONITOR_PID}" || true; fi
set -e
printf 'EXIT_CODE=%s\nFINISHED_AT=%s\n' "${RC}" "$(date '+%F %T %Z')" > "${RUN_ROOT}/trial_exit.status"

if [[ -d "${RUN_ROOT}/train" ]]; then
  PYTHONPATH="${ROOT}/verl" python3 -m mas_loop_rl.analyze_vllm_concurrency_run \
    "${RUN_ROOT}" --output "${RUN_ROOT}/concurrency_summary.json" || true
fi
exit "${RC}"
