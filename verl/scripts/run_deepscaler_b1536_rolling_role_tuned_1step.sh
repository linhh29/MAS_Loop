#!/usr/bin/env bash
set -euo pipefail
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

# Balanced ~70% KV follow-up after b1536 showed updated-subagent KV ~=100% and
# 2216 preemptions at active=8192. Keep task batch, sequence lengths, rollout
# group and Ray admission fixed. Measured peak running was 7676 for Sub-agent
# and 3368 for Editor; caps 5632/3072 target roughly 70-75% peak KV without
# starving rolling refill. max_num_seqs is bounded near the useful active cap
# instead of the previous unnecessary 8k/12k scheduler capacity.
ROOT=/path/to/MAS_Loop
[[ "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" == "${ROOT}" ]] || exit 2
TS=${DS_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
RUN_ROOT=${DS_RUN_ROOT:-/path/to/checkpoints/benchmarks/deepscaler_b1536_rolling_role_tuned_${TS}}
exec env \
  DS_TIMESTAMP="${TS}" DS_RUN_ROOT="${RUN_ROOT}" \
  BENCH_NUM_STEPS=1 BENCH_ROLLOUT_N=8 BENCH_RUN_EDITOR=1 \
  BENCH_EDITOR_TRAIN_BATCH_SIZE=12288 BENCH_PPO_MINI_BATCH_SIZE=256 \
  BENCH_RAY_SERVER_MAX_CONCURRENCY=4096 BENCH_RAY_GENERATE_MAX_OUTSTANDING=4096 \
  BENCH_ROLLOUT_MAX_NUM_SEQS=4096 BENCH_PEER_MAX_NUM_SEQS=6144 BENCH_SUB_AGENT_MAX_NUM_SEQS=6144 \
  BENCH_MAX_CONCURRENCY=6144 BENCH_DISPATCH_WORKERS=768 \
  BENCH_ORCHESTRA_VLLM_MAX_ACTIVE=4096 BENCH_EDITOR_VLLM_MAX_ACTIVE=3072 BENCH_SUB_AGENT_VLLM_MAX_ACTIVE=5632 \
  BENCH_ROLLOUT_MAX_NUM_BATCHED_TOKENS=98304 BENCH_PEER_MAX_NUM_BATCHED_TOKENS=196608 BENCH_SUB_AGENT_MAX_NUM_BATCHED_TOKENS=196608 \
  BENCH_ROLLOUT_GPU_MEM_UTIL=0.85 BENCH_PEER_GPU_MEMORY_UTILIZATION=0.90 BENCH_SUB_AGENT_GPU_MEMORY_UTILIZATION=0.90 \
  BENCH_HTTP_TRANSPORT=urllib3 BENCH_HTTP_POOL_MAXSIZE=1024 \
  BENCH_ORCHESTRA_HTTP_POOL_MAXSIZE=768 BENCH_EDITOR_HTTP_POOL_MAXSIZE=512 BENCH_SUBAGENT_HTTP_POOL_MAXSIZE=1024 \
  BENCH_HTTP_CONNECT_TIMEOUT_SEC=30 BENCH_HTTP_POOL_TIMEOUT_SEC=120 \
  BENCH_TQ_DATA_UPDATE_MAX_CONCURRENCY=64 BENCH_TQ_DATA_UPDATE_MAX_RETRIES=3 BENCH_TQ_DATA_UPDATE_RETRY_BACKOFF_SEC=0.25 \
  BENCH_VLLM_HTTP_BACKLOG=16384 BENCH_VLLM_HTTP_TIMEOUT_KEEP_ALIVE=60 \
  BENCH_ACTOR_GUIDED_JSON=0 BENCH_EDITOR_AGENT_OUTPUT_CHARS=2400 \
  BENCH_EDITOR_AGENT_ERROR_CHARS=800 BENCH_EDITOR_FINAL_OUTPUT_CHARS=4000 \
  BENCH_RUNTIME_MONITOR=1 BENCH_RUNTIME_MONITOR_INTERVAL=5 \
  GPU_ISOLATION_CHECK_INTERVAL=5 GPU_ISOLATION_STABLE_CHECKS=2 \
  bash "${ROOT}/verl/scripts/run_deepscaler_vllm_concurrency_trial.sh" 1536 "$@"
