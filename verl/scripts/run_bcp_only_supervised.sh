#!/usr/bin/env bash
set -euo pipefail
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

# BrowseComp-Plus-only full-training supervisor.  This file deliberately owns
# only BCP_* configuration so generic variables left by another VERL project
# cannot alter this run.
BCP_MAS_ROOT=${BCP_MAS_ROOT:-/path/to/MAS_Loop}
BCP_VERL_ROOT=${BCP_VERL_ROOT:-${BCP_MAS_ROOT}/verl}
BCP_ALL_GPUS=${BCP_ALL_GPUS:-8,9,10,11,12,13,14,15}
BCP_TIMESTAMP=${BCP_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
BCP_CKPT_ROOT=${BCP_CKPT_ROOT:-/path/to/checkpoints/bcp/${BCP_TIMESTAMP}}
BCP_RUN_ROOT=${BCP_RUN_ROOT:-${BCP_CKPT_ROOT}}
BCP_SESSION=${BCP_SESSION:-masloop_bcp_full_${BCP_TIMESTAMP}}
BCP_MONITOR_SESSION=${BCP_MONITOR_SESSION:-${BCP_SESSION}}
BCP_MONITOR_INTERVAL_SEC=${BCP_MONITOR_INTERVAL_SEC:-1800}
BCP_METRICS_INTERVAL_SEC=${BCP_METRICS_INTERVAL_SEC:-60}
BCP_GPU_WAIT_INTERVAL_SEC=${BCP_GPU_WAIT_INTERVAL_SEC:-15}
BCP_GPU_STABLE_CHECKS=${BCP_GPU_STABLE_CHECKS:-2}
BCP_GPU_WAIT_TIMEOUT_SEC=${BCP_GPU_WAIT_TIMEOUT_SEC:-0}
BCP_ORIGINAL_SAMPLES=${BCP_ORIGINAL_SAMPLES:-662}
BCP_EXPECTED_SAMPLES=${BCP_EXPECTED_SAMPLES:-768}
BCP_TRAIN_BATCH_SIZE=${BCP_TRAIN_BATCH_SIZE:-128}
BCP_ROLLOUT_N=${BCP_ROLLOUT_N:-8}
BCP_EDITOR_GROUP_SIZE=${BCP_EDITOR_GROUP_SIZE:-8}
BCP_EDITOR_TRAIN_BATCH_SIZE=${BCP_EDITOR_TRAIN_BATCH_SIZE:-$((BCP_TRAIN_BATCH_SIZE * BCP_ROLLOUT_N))}
BCP_PPO_MINI_BATCH_SIZE=${BCP_PPO_MINI_BATCH_SIZE:-128}
BCP_PPO_MICRO_BATCH_SIZE_PER_GPU=${BCP_PPO_MICRO_BATCH_SIZE_PER_GPU:-4}
BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-8}
BCP_NUM_CHECKPOINTS=${BCP_NUM_CHECKPOINTS:-10}
BCP_SAVE_FREQ=${BCP_SAVE_FREQ:-250}
BCP_RUN_ORCHESTRA=${BCP_RUN_ORCHESTRA:-1}
BCP_RUN_EDITOR=${BCP_RUN_EDITOR:-1}
BCP_SKIP_PREPARE_DATA=${BCP_SKIP_PREPARE_DATA:-0}
BCP_MODEL_PATH=${BCP_MODEL_PATH:-/path/to/models/Qwen3-8B}
BCP_ORCHESTRA_MODEL=${BCP_ORCHESTRA_MODEL:-${BCP_MODEL_PATH}}
BCP_EDITOR_MODEL=${BCP_EDITOR_MODEL:-${BCP_MODEL_PATH}}
BCP_JUDGE_MODEL=${BCP_JUDGE_MODEL:-/path/to/models/Qwen3-30B-A3B}
BCP_JUDGE_GPU_MEMORY_UTILIZATION=${BCP_JUDGE_GPU_MEMORY_UTILIZATION:-0.78}
BCP_JUDGE_MAX_NUM_SEQS=${BCP_JUDGE_MAX_NUM_SEQS:-256}
BCP_JUDGE_MAX_NUM_BATCHED_TOKENS=${BCP_JUDGE_MAX_NUM_BATCHED_TOKENS:-49152}
BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS=${BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS:-1}
BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS=${BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS:-1}
BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD=${BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD:-1024}
BCP_JUDGE_MAX_MODEL_LEN=${BCP_JUDGE_MAX_MODEL_LEN:-23192}
BCP_JUDGE_MAX_TOKENS=${BCP_JUDGE_MAX_TOKENS:-4096}
BCP_JUDGE_VLLM_MAX_ACTIVE=${BCP_JUDGE_VLLM_MAX_ACTIVE:-256}
BCP_JUDGE_HTTP_POOL_MAXSIZE=${BCP_JUDGE_HTTP_POOL_MAXSIZE:-384}
BCP_JUDGE_PORT=${BCP_JUDGE_PORT:-8513}
BCP_MAX_TRAIN_ROWS=${BCP_MAX_TRAIN_ROWS:-0}
BCP_RAY_DASHBOARD_PORT=${BCP_RAY_DASHBOARD_PORT:-8525}
BCP_RAY_TEMP_DIR=${BCP_RAY_TEMP_DIR:-/tmp/mas_loop_bcp_ray_${BCP_TIMESTAMP}}
BCP_CONTROL_DIR=${BCP_CONTROL_DIR:-/tmp/mas_loop_bcp_control_${BCP_TIMESTAMP}}
BCP_CONTROL_SOCKET=${BCP_CONTROL_SOCKET:-${BCP_CONTROL_DIR}/coordinator.sock}
BCP_SLEEP_LOCK=${BCP_SLEEP_LOCK:-${BCP_CONTROL_DIR}/fallback.lock}
BCP_SLEEP_STATE=${BCP_SLEEP_STATE:-${BCP_CONTROL_DIR}/state.json}
BCP_SLEEP_EVENTS=${BCP_SLEEP_EVENTS:-${BCP_CONTROL_DIR}/events.jsonl}
BCP_SLEEP_EVENTS_DURABLE=${BCP_SLEEP_EVENTS_DURABLE:-${BCP_RUN_ROOT}/vllm_sleep/events.jsonl}

[[ "${BCP_MAS_ROOT}" == "/path/to/MAS_Loop" ]] || { echo "[BCP-SUP] wrong root: ${BCP_MAS_ROOT}" >&2; exit 2; }
[[ "${BCP_ALL_GPUS}" == "8,9,10,11,12,13,14,15" ]] || { echo "[BCP-SUP] only physical GPUs 8-15 are allowed" >&2; exit 2; }
[[ -x "${BCP_VERL_ROOT}/scripts/run_bcp_mas_loop_full.sh" ]] || { echo "[BCP-SUP] missing BCP full launcher" >&2; exit 2; }
[[ -f "${BCP_MAS_ROOT}/datasets/BrowseComp-Plus/data/browsecomp_plus_train.jsonl" ]] || exit 2
[[ -f "${BCP_MAS_ROOT}/datasets/BrowseComp-Plus/scripts_build_index/indexes/bm25/documents.jsonl" || -d "${BCP_MAS_ROOT}/datasets/BrowseComp-Plus/scripts_build_index/indexes/bm25" ]] || { echo "[BCP-SUP] missing local BM25 index" >&2; exit 2; }
[[ -f /path/to/models/Qwen3-8B/config.json && -f /path/to/models/Qwen3-30B-A3B/config.json ]] || { echo "[BCP-SUP] missing local Qwen models under /path/to/models" >&2; exit 2; }
[[ -f "${BCP_JUDGE_MODEL}/config.json" ]] || { echo "[BCP-SUP] missing local judge model: ${BCP_JUDGE_MODEL}" >&2; exit 2; }
(( BCP_ROLLOUT_N == 8 && BCP_EDITOR_GROUP_SIZE == 8 )) || { echo "[BCP-SUP] rollout/group size must stay 8" >&2; exit 2; }
(( BCP_TRAIN_BATCH_SIZE >= 96 && BCP_TRAIN_BATCH_SIZE <= 128 && BCP_TRAIN_BATCH_SIZE % 8 == 0 )) || { echo "[BCP-SUP] BCP batch must be 96..128 and divisible by 8; default remains 128" >&2; exit 2; }
(( BCP_JUDGE_MAX_TOKENS == 4096 )) || { echo "[BCP-SUP] judge max output ceiling must remain 4096" >&2; exit 2; }
mkdir -p "${BCP_RUN_ROOT}/logs" "${BCP_RUN_ROOT}/data" "${BCP_RUN_ROOT}/monitor" "${BCP_RUN_ROOT}/metrics" "${BCP_CONTROL_DIR}" "$(dirname "${BCP_SLEEP_EVENTS_DURABLE}")"

publish_monitor_env() {
  local tmp="${BCP_RUN_ROOT}/current_mas_loop_job.env.tmp.$$"
  cat > "${tmp}" <<MON
RUN_DIR=${BCP_RUN_ROOT}
CHECKPOINT_ROOT=${BCP_CKPT_ROOT}
RUN_NAME=$(basename "${BCP_RUN_ROOT}")
GPU_SET=${BCP_ALL_GPUS}
LAUNCH_SCRIPT=${BCP_VERL_ROOT}/scripts/run_bcp_only_supervised.sh
START_TIME=$(date +%s)
SESSION=${BCP_MONITOR_SESSION}
DATASET=bcp
EXPECTED_SAMPLES=${BCP_EXPECTED_SAMPLES}
ORIGINAL_SAMPLES=${BCP_ORIGINAL_SAMPLES}
PAIR_GROUP_SIZE=${BCP_EDITOR_GROUP_SIZE}
MODE=full_train
VLLM_SLEEP_STATE=${BCP_SLEEP_STATE}
VLLM_SLEEP_EVENTS=${BCP_SLEEP_EVENTS}
MON
  mv -f "${tmp}" "${BCP_RUN_ROOT}/current_mas_loop_job.env"
}

monitor_loop() {
  local sleep_pid=""
  trap '
    if [[ -n "${sleep_pid}" ]]; then
      kill "${sleep_pid}" 2>/dev/null || true
      wait "${sleep_pid}" 2>/dev/null || true
    fi
    exit 0
  ' TERM INT

  while true; do
    local now
    now=$(date '+%F %T %Z')
    {
      echo "========== BCP supervisor check ${now} =========="
      gpustat --no-color -p 2>/dev/null | awk 'NR==1 || /^\[(8|9|10|11|12|13|14|15)\]/' || true
      ps -eo pid,ppid,etime,stat,cmd | grep -E '/path/to/MAS_Loop|mas_loop_rl|verl.trainer.main_ppo|vllm.entrypoints.openai.api_server' | grep -v grep || true
    } >> "${BCP_RUN_ROOT}/monitor/status_30min.log" 2>&1
    gpustat --json >> "${BCP_RUN_ROOT}/monitor/gpustat.jsonl" 2>/dev/null || true
    sleep "${BCP_MONITOR_INTERVAL_SEC}" &
    sleep_pid=$!
    wait "${sleep_pid}" || return 0
    sleep_pid=""
  done
}

publish_monitor_env
monitor_loop &
BCP_MONITOR_PID=$!
python3 "${BCP_VERL_ROOT}/mas_loop_rl/metrics_monitor.py" \
  --log-file "${BCP_RUN_ROOT}/logs/full_train.log" \
  --output-dir "${BCP_RUN_ROOT}/metrics" \
  --interval "${BCP_METRICS_INTERVAL_SEC}" \
  >> "${BCP_RUN_ROOT}/monitor/metrics_monitor.log" 2>&1 &
BCP_METRICS_PID=$!
cleanup() {
  trap - EXIT INT TERM
  kill "${BCP_MONITOR_PID}" "${BCP_METRICS_PID}" 2>/dev/null || true
  wait "${BCP_MONITOR_PID}" 2>/dev/null || true
  wait "${BCP_METRICS_PID}" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

cat > "${BCP_RUN_ROOT}/launch_config.env" <<CFG
BCP_MAS_ROOT=${BCP_MAS_ROOT}
BCP_VERL_ROOT=${BCP_VERL_ROOT}
BCP_ALL_GPUS=${BCP_ALL_GPUS}
BCP_RUN_DIR=${BCP_RUN_ROOT}
BCP_CKPT_ROOT=${BCP_CKPT_ROOT}
BCP_SESSION=${BCP_SESSION}
BCP_ORIGINAL_SAMPLES=${BCP_ORIGINAL_SAMPLES}
BCP_EXPECTED_SAMPLES=${BCP_EXPECTED_SAMPLES}
BCP_TRAIN_BATCH_SIZE=${BCP_TRAIN_BATCH_SIZE}
BCP_EDITOR_TRAIN_BATCH_SIZE=${BCP_EDITOR_TRAIN_BATCH_SIZE}
BCP_ROLLOUT_N=${BCP_ROLLOUT_N}
BCP_EDITOR_GROUP_SIZE=${BCP_EDITOR_GROUP_SIZE}
BCP_PPO_MINI_BATCH_SIZE=${BCP_PPO_MINI_BATCH_SIZE}
BCP_PPO_MICRO_BATCH_SIZE_PER_GPU=${BCP_PPO_MICRO_BATCH_SIZE_PER_GPU}
BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=${BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU}
BCP_NUM_CHECKPOINTS=${BCP_NUM_CHECKPOINTS}
BCP_SAVE_FREQ=${BCP_SAVE_FREQ}
BCP_RUN_ORCHESTRA=${BCP_RUN_ORCHESTRA}
BCP_RUN_EDITOR=${BCP_RUN_EDITOR}
BCP_SKIP_PREPARE_DATA=${BCP_SKIP_PREPARE_DATA}
BCP_MODEL_PATH=${BCP_MODEL_PATH}
BCP_ORCHESTRA_MODEL=${BCP_ORCHESTRA_MODEL}
BCP_EDITOR_MODEL=${BCP_EDITOR_MODEL}
BCP_JUDGE_MODEL=${BCP_JUDGE_MODEL}
BCP_JUDGE_GPU_MEMORY_UTILIZATION=${BCP_JUDGE_GPU_MEMORY_UTILIZATION}
BCP_JUDGE_MAX_NUM_SEQS=${BCP_JUDGE_MAX_NUM_SEQS}
BCP_JUDGE_MAX_NUM_BATCHED_TOKENS=${BCP_JUDGE_MAX_NUM_BATCHED_TOKENS}
BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS=${BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS}
BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS=${BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS}
BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD=${BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD}
BCP_JUDGE_MAX_MODEL_LEN=${BCP_JUDGE_MAX_MODEL_LEN}
BCP_JUDGE_MAX_TOKENS=${BCP_JUDGE_MAX_TOKENS}
BCP_JUDGE_VLLM_MAX_ACTIVE=${BCP_JUDGE_VLLM_MAX_ACTIVE}
BCP_JUDGE_HTTP_POOL_MAXSIZE=${BCP_JUDGE_HTTP_POOL_MAXSIZE}
BCP_JUDGE_PORT=${BCP_JUDGE_PORT}
BCP_MAX_TRAIN_ROWS=${BCP_MAX_TRAIN_ROWS}
BCP_RAY_DASHBOARD_PORT=${BCP_RAY_DASHBOARD_PORT}
BCP_RAY_TEMP_DIR=${BCP_RAY_TEMP_DIR}
CFG

# Fail closed: a sleeping foreign vLLM can show almost zero memory and later
# wake.  The helper checks both GPU process ownership and foreign project roots.
echo "[BCP-SUP] waiting for isolated physical GPUs ${BCP_ALL_GPUS} at $(date '+%F %T %Z')" | tee "${BCP_RUN_ROOT}/monitor/gpu_isolation.log"
PYTHONPATH="${BCP_VERL_ROOT}:${BCP_MAS_ROOT}:${PYTHONPATH:-}" \
python3 -m mas_loop_rl.wait_for_gpu_isolation \
  --gpus "${BCP_ALL_GPUS}" --interval "${BCP_GPU_WAIT_INTERVAL_SEC}" \
  --stable-checks "${BCP_GPU_STABLE_CHECKS}" --timeout "${BCP_GPU_WAIT_TIMEOUT_SEC}" \
  | tee -a "${BCP_RUN_ROOT}/monitor/gpu_isolation.log"

echo "[BCP-SUP] starting isolated BCP full train at $(date '+%F %T %Z')"
echo "[BCP-SUP] session=${BCP_SESSION} run_root=${BCP_RUN_ROOT} gpus=${BCP_ALL_GPUS}"
set +e
env \
  BCP_MAS_ROOT="${BCP_MAS_ROOT}" BCP_VERL_ROOT="${BCP_VERL_ROOT}" BCP_ALL_GPUS="${BCP_ALL_GPUS}" \
  BCP_TIMESTAMP="${BCP_TIMESTAMP}" BCP_CKPT_ROOT="${BCP_CKPT_ROOT}" BCP_RUN_DIR="${BCP_RUN_ROOT}" BCP_LOG_DIR="${BCP_RUN_ROOT}/logs" BCP_DATA_DIR="${BCP_RUN_ROOT}/data" \
  BCP_TRAIN_BATCH_SIZE="${BCP_TRAIN_BATCH_SIZE}" BCP_EDITOR_TRAIN_BATCH_SIZE="${BCP_EDITOR_TRAIN_BATCH_SIZE}" \
  BCP_ROLLOUT_N="${BCP_ROLLOUT_N}" BCP_EDITOR_GROUP_SIZE="${BCP_EDITOR_GROUP_SIZE}" \
  BCP_PPO_MINI_BATCH_SIZE="${BCP_PPO_MINI_BATCH_SIZE}" BCP_PPO_MICRO_BATCH_SIZE_PER_GPU="${BCP_PPO_MICRO_BATCH_SIZE_PER_GPU}" \
  BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU="${BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU}" \
  BCP_NUM_CHECKPOINTS="${BCP_NUM_CHECKPOINTS}" BCP_SAVE_FREQ="${BCP_SAVE_FREQ}" \
  BCP_RUN_ORCHESTRA="${BCP_RUN_ORCHESTRA}" BCP_RUN_EDITOR="${BCP_RUN_EDITOR}" BCP_SKIP_PREPARE_DATA="${BCP_SKIP_PREPARE_DATA}" \
  BCP_MODEL_PATH="${BCP_MODEL_PATH}" BCP_ORCHESTRA_MODEL="${BCP_ORCHESTRA_MODEL}" BCP_EDITOR_MODEL="${BCP_EDITOR_MODEL}" BCP_JUDGE_MODEL="${BCP_JUDGE_MODEL}" \
  BCP_JUDGE_GPU_MEMORY_UTILIZATION="${BCP_JUDGE_GPU_MEMORY_UTILIZATION}" BCP_JUDGE_MAX_NUM_SEQS="${BCP_JUDGE_MAX_NUM_SEQS}" BCP_JUDGE_MAX_NUM_BATCHED_TOKENS="${BCP_JUDGE_MAX_NUM_BATCHED_TOKENS}" \
  BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS="${BCP_JUDGE_MAX_NUM_PARTIAL_PREFILLS}" BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS="${BCP_JUDGE_MAX_LONG_PARTIAL_PREFILLS}" BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD="${BCP_JUDGE_LONG_PREFILL_TOKEN_THRESHOLD}" \
  BCP_JUDGE_MAX_MODEL_LEN="${BCP_JUDGE_MAX_MODEL_LEN}" BCP_JUDGE_MAX_TOKENS="${BCP_JUDGE_MAX_TOKENS}" BCP_JUDGE_VLLM_MAX_ACTIVE="${BCP_JUDGE_VLLM_MAX_ACTIVE}" BCP_JUDGE_HTTP_POOL_MAXSIZE="${BCP_JUDGE_HTTP_POOL_MAXSIZE}" BCP_JUDGE_PORT="${BCP_JUDGE_PORT}" \
  BCP_MAX_TRAIN_ROWS="${BCP_MAX_TRAIN_ROWS}" BCP_RAY_DASHBOARD_PORT="${BCP_RAY_DASHBOARD_PORT}" BCP_RAY_TEMP_DIR="${BCP_RAY_TEMP_DIR}" \
  BCP_CONTROL_DIR="${BCP_CONTROL_DIR}" BCP_CONTROL_SOCKET="${BCP_CONTROL_SOCKET}" BCP_SLEEP_LOCK="${BCP_SLEEP_LOCK}" \
  BCP_SLEEP_STATE="${BCP_SLEEP_STATE}" BCP_SLEEP_EVENTS="${BCP_SLEEP_EVENTS}" BCP_SLEEP_EVENTS_DURABLE="${BCP_SLEEP_EVENTS_DURABLE}" \
  bash "${BCP_VERL_ROOT}/scripts/run_bcp_mas_loop_full.sh" "$@" 2>&1 | tee "${BCP_RUN_ROOT}/logs/full_train.log"
rc=${PIPESTATUS[0]}
set -e
printf 'TRAIN_EXIT_CODE=%s\nEXIT_CODE=%s\nFINISHED_AT=%s\n' "${rc}" "${rc}" "$(date '+%F %T %Z')" > "${BCP_RUN_ROOT}/exit.status"
echo "[BCP-SUP] BCP full exited rc=${rc} at $(date '+%F %T %Z')"
exit "${rc}"
