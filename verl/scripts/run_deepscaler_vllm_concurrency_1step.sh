#!/usr/bin/env bash
set -euo pipefail
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

# DeepScaleR one/multi optimizer-step wrapper used by the concurrency trial.
# It only maps BENCH_* inputs into the independent DS_* namespace; the canonical
# DeepScaleR launcher performs validation, data preparation, and training.
ROOT=/path/to/MAS_Loop
[[ "$(readlink -f "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)")" == "$(readlink -f "${ROOT}")" ]] || {
  echo "Refusing to run outside ${ROOT}" >&2
  exit 2
}

TS=${DS_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
BATCH=${BENCH_TRAIN_BATCH_SIZE:-128}
ROLLOUT_N=${BENCH_ROLLOUT_N:-8}
NUM_STEPS=${BENCH_NUM_STEPS:-1}
RUN_EDITOR=${BENCH_RUN_EDITOR:-0}
(( BATCH > 0 && BATCH % 8 == 0 )) || { echo "DeepScaleR benchmark batch must be a positive multiple of 8" >&2; exit 2; }
(( ROLLOUT_N == 8 )) || { echo "DeepScaleR benchmark requires rollout_n=8" >&2; exit 2; }
(( NUM_STEPS > 0 )) || { echo "BENCH_NUM_STEPS must be positive" >&2; exit 2; }

MAX_ROWS=$((BATCH * NUM_STEPS))
EDITOR_BATCH=${BENCH_EDITOR_TRAIN_BATCH_SIZE:-$((BATCH * ROLLOUT_N))}
PPO_MINI=${BENCH_PPO_MINI_BATCH_SIZE:-128}
RUN_ROOT=${DS_RUN_ROOT:-/path/to/checkpoints/benchmarks/deepscaler_b${BATCH}_c128_1step_${TS}}
RUN_DIR=${DS_RUN_DIR:-${RUN_ROOT}/train}

exec env \
  DS_MAS_ROOT="${ROOT}" DS_VERL_ROOT="${ROOT}/verl" DS_ALL_GPUS=8,9,10,11,12,13,14,15 \
  DS_TIMESTAMP="${TS}" DS_RUN_DIR="${RUN_DIR}" DS_CKPT_ROOT="${RUN_DIR}/checkpoints" DS_DATA_DIR="${RUN_DIR}/data" DS_LOG_DIR="${RUN_DIR}/logs" \
  DS_TRAIN_BATCH_SIZE="${BATCH}" DS_EDITOR_TRAIN_BATCH_SIZE="${EDITOR_BATCH}" \
  DS_PPO_MINI_BATCH_SIZE="${PPO_MINI}" \
  DS_PPO_MICRO_BATCH_SIZE_PER_GPU="${BENCH_PPO_MICRO_BATCH_SIZE_PER_GPU:-2}" \
  DS_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU="${BENCH_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-4}" \
  DS_ROLLOUT_N="${ROLLOUT_N}" DS_TOTAL_EPOCHS=1 DS_ADVERSARIAL_ROUNDS=1 \
  DS_MAX_TRAIN_ROWS="${MAX_ROWS}" DS_DATA_PAD_TO_MULTIPLE="${BATCH}" DS_DATA_VAL_RATIO=0 \
  DS_RUN_ORCHESTRA=1 DS_RUN_EDITOR="${RUN_EDITOR}" DS_SAVE_FREQ=-1 DS_NUM_CHECKPOINTS=0 \
  DS_ROLLOUT_MAX_NUM_SEQS="${BENCH_ROLLOUT_MAX_NUM_SEQS:-128}" \
  DS_PEER_MAX_NUM_SEQS="${BENCH_PEER_MAX_NUM_SEQS:-128}" \
  DS_SUB_AGENT_MAX_NUM_SEQS="${BENCH_SUB_AGENT_MAX_NUM_SEQS:-128}" \
  DS_ROLLOUT_MAX_NUM_BATCHED_TOKENS="${BENCH_ROLLOUT_MAX_NUM_BATCHED_TOKENS:-32768}" \
  DS_PEER_MAX_NUM_BATCHED_TOKENS="${BENCH_PEER_MAX_NUM_BATCHED_TOKENS:-32768}" \
  DS_SUB_AGENT_MAX_NUM_BATCHED_TOKENS="${BENCH_SUB_AGENT_MAX_NUM_BATCHED_TOKENS:-32768}" \
  DS_ROLLOUT_GPU_MEM_UTIL="${BENCH_ROLLOUT_GPU_MEM_UTIL:-0.85}" \
  DS_PEER_GPU_MEMORY_UTILIZATION="${BENCH_PEER_GPU_MEMORY_UTILIZATION:-0.90}" \
  DS_SUB_AGENT_GPU_MEMORY_UTILIZATION="${BENCH_SUB_AGENT_GPU_MEMORY_UTILIZATION:-0.90}" \
  DS_MAX_CONCURRENCY="${BENCH_MAX_CONCURRENCY:-128}" \
  DS_VLLM_MAX_ACTIVE="${BENCH_VLLM_MAX_ACTIVE:-128}" \
  DS_ORCHESTRA_VLLM_MAX_ACTIVE="${BENCH_ORCHESTRA_VLLM_MAX_ACTIVE:-128}" \
  DS_EDITOR_VLLM_MAX_ACTIVE="${BENCH_EDITOR_VLLM_MAX_ACTIVE:-128}" \
  DS_SUB_AGENT_VLLM_MAX_ACTIVE="${BENCH_SUB_AGENT_VLLM_MAX_ACTIVE:-128}" \
  DS_RAY_SERVER_MAX_CONCURRENCY="${BENCH_RAY_SERVER_MAX_CONCURRENCY:-128}" \
  DS_RAY_GENERATE_MAX_OUTSTANDING="${BENCH_RAY_GENERATE_MAX_OUTSTANDING:-128}" \
  DS_DISPATCH_WORKERS_PER_PROCESS="${BENCH_DISPATCH_WORKERS:-128}" \
  DS_HTTP_POOL_MAXSIZE="${BENCH_HTTP_POOL_MAXSIZE:-128}" \
  DS_ORCHESTRA_HTTP_POOL_MAXSIZE="${BENCH_ORCHESTRA_HTTP_POOL_MAXSIZE:-128}" \
  DS_EDITOR_HTTP_POOL_MAXSIZE="${BENCH_EDITOR_HTTP_POOL_MAXSIZE:-128}" \
  DS_SUBAGENT_HTTP_POOL_MAXSIZE="${BENCH_SUBAGENT_HTTP_POOL_MAXSIZE:-128}" \
  DS_TQ_DATA_UPDATE_MAX_CONCURRENCY="${BENCH_TQ_DATA_UPDATE_MAX_CONCURRENCY:-128}" \
  DS_ROLLOUT_DISABLE_LOG_STATS=0 \
  bash "${ROOT}/verl/scripts/run_deepscaler_mas_loop_full.sh" "$@"
