#!/usr/bin/env bash
set -euo pipefail
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

# BCP-specific one/multi optimizer-step benchmark. This deliberately calls the
# BCP wrapper (not the DeepScaleR wrapper), so the real five-turn BM25 retrieval
# path and all BCP_* parameter isolation remain active.
ROOT=/path/to/MAS_Loop
[[ "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" == "${ROOT}" ]] || exit 2

TS=${BCP_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
BATCH=${BENCH_TRAIN_BATCH_SIZE:-128}
ROLLOUT_N=${BENCH_ROLLOUT_N:-8}
NUM_STEPS=${BENCH_NUM_STEPS:-1}
RUN_EDITOR=${BENCH_RUN_EDITOR:-1}
(( BATCH > 0 && BATCH % 8 == 0 )) || { echo "BCP benchmark batch must be a positive multiple of 8" >&2; exit 2; }
(( ROLLOUT_N == 8 )) || { echo "BCP benchmark requires rollout_n=8" >&2; exit 2; }
(( NUM_STEPS > 0 )) || { echo "BENCH_NUM_STEPS must be positive" >&2; exit 2; }
MAX_ROWS=$((BATCH * NUM_STEPS))
EDITOR_BATCH=${BENCH_EDITOR_TRAIN_BATCH_SIZE:-$((BATCH * ROLLOUT_N))}
PPO_MINI=${BENCH_PPO_MINI_BATCH_SIZE:-${BATCH}}
RUN_ROOT=${BCP_RUN_ROOT:-/path/to/checkpoints/benchmarks/bcp_concurrency_b${BATCH}_${TS}}
RUN_DIR=${BCP_RUN_DIR:-${RUN_ROOT}/train}

exec env \
  BCP_MAS_ROOT="${ROOT}" BCP_VERL_ROOT="${ROOT}/verl" BCP_ALL_GPUS=8,9,10,11,12,13,14,15 \
  BCP_TIMESTAMP="${TS}" BCP_RUN_DIR="${RUN_DIR}" BCP_DATA_DIR="${RUN_DIR}/data" BCP_LOG_DIR="${RUN_DIR}/logs" \
  BCP_TRAIN_BATCH_SIZE="${BATCH}" BCP_EDITOR_TRAIN_BATCH_SIZE="${EDITOR_BATCH}" \
  BCP_PPO_MINI_BATCH_SIZE="${PPO_MINI}" \
  BCP_PPO_MICRO_BATCH_SIZE_PER_GPU="${BENCH_PPO_MICRO_BATCH_SIZE_PER_GPU:-4}" \
  BCP_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU="${BENCH_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU:-8}" \
  BCP_ROLLOUT_N="${ROLLOUT_N}" BCP_EDITOR_GROUP_SIZE=8 BCP_TOTAL_EPOCHS=1 BCP_ADVERSARIAL_ROUNDS=1 \
  BCP_MAX_PROMPT_LENGTH=15000 BCP_MAX_RESPONSE_LENGTH=8192 BCP_ROLLOUT_MAX_MODEL_LEN=23192 \
  BCP_MAX_TRAIN_ROWS="${MAX_ROWS}" BCP_DATA_PAD_TO_MULTIPLE="${BATCH}" BCP_DATA_VAL_RATIO=0 \
  BCP_RUN_ORCHESTRA=1 BCP_RUN_EDITOR="${RUN_EDITOR}" \
  BCP_SAVE_FREQ=-1 BCP_NUM_INTERMEDIATE_CHECKPOINTS=0 \
  BCP_ROLLOUT_MAX_NUM_SEQS="${BENCH_ROLLOUT_MAX_NUM_SEQS:-512}" \
  BCP_PEER_MAX_NUM_SEQS="${BENCH_PEER_MAX_NUM_SEQS:-768}" \
  BCP_SUB_AGENT_MAX_NUM_SEQS="${BENCH_SUB_AGENT_MAX_NUM_SEQS:-1024}" \
  BCP_ROLLOUT_MAX_NUM_BATCHED_TOKENS="${BENCH_ROLLOUT_MAX_NUM_BATCHED_TOKENS:-65536}" \
  BCP_PEER_MAX_NUM_BATCHED_TOKENS="${BENCH_PEER_MAX_NUM_BATCHED_TOKENS:-98304}" \
  BCP_SUB_AGENT_MAX_NUM_BATCHED_TOKENS="${BENCH_SUB_AGENT_MAX_NUM_BATCHED_TOKENS:-98304}" \
  BCP_ROLLOUT_GPU_MEM_UTIL="${BENCH_ROLLOUT_GPU_MEM_UTIL:-0.85}" \
  BCP_PEER_GPU_MEMORY_UTILIZATION="${BENCH_PEER_GPU_MEMORY_UTILIZATION:-0.90}" \
  BCP_SUB_AGENT_GPU_MEMORY_UTILIZATION="${BENCH_SUB_AGENT_GPU_MEMORY_UTILIZATION:-0.90}" \
  BCP_MAX_CONCURRENCY="${BENCH_MAX_CONCURRENCY:-1024}" \
  BCP_VLLM_MAX_ACTIVE="${BENCH_VLLM_MAX_ACTIVE:-1024}" \
  BCP_ORCHESTRA_VLLM_MAX_ACTIVE="${BENCH_ORCHESTRA_VLLM_MAX_ACTIVE:-768}" \
  BCP_EDITOR_VLLM_MAX_ACTIVE="${BENCH_EDITOR_VLLM_MAX_ACTIVE:-768}" \
  BCP_SUB_AGENT_VLLM_MAX_ACTIVE="${BENCH_SUB_AGENT_VLLM_MAX_ACTIVE:-1024}" \
  BCP_RAY_SERVER_MAX_CONCURRENCY="${BENCH_RAY_SERVER_MAX_CONCURRENCY:-1024}" \
  BCP_RAY_GENERATE_MAX_OUTSTANDING="${BENCH_RAY_GENERATE_MAX_OUTSTANDING:-1024}" \
  BCP_DISPATCH_WORKERS_PER_PROCESS="${BENCH_DISPATCH_WORKERS:-128}" \
  BCP_HTTP_POOL_MAXSIZE="${BENCH_HTTP_POOL_MAXSIZE:-512}" \
  BCP_ORCHESTRA_HTTP_POOL_MAXSIZE="${BENCH_ORCHESTRA_HTTP_POOL_MAXSIZE:-512}" \
  BCP_EDITOR_HTTP_POOL_MAXSIZE="${BENCH_EDITOR_HTTP_POOL_MAXSIZE:-384}" \
  BCP_SUBAGENT_HTTP_POOL_MAXSIZE="${BENCH_SUBAGENT_HTTP_POOL_MAXSIZE:-1024}" \
  BCP_ROLLOUT_DISABLE_LOG_STATS=0 \
  BCP_RAY_TEMP_DIR="${BENCH_RAY_TEMP_DIR:-/dev/shm/mas_loop_bcp_${TS}}" \
  bash "${ROOT}/verl/scripts/run_bcp_mas_loop_full.sh" "$@"
