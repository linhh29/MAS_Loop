#!/usr/bin/env bash
set -euo pipefail

# Two-step throughput benchmark after SSE/structured-retry/profiling fixes.
# It is isolated to MAS_Loop, local /tmp models, and physical GPUs 8-15.
ROOT=/path/to/MAS_Loop
[[ "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)" == "${ROOT}" ]] || {
  echo "Refusing to run outside ${ROOT}" >&2; exit 2;
}
TS=${DS_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
RUN_ROOT=${DS_RUN_ROOT:-/path/to/checkpoints/benchmarks/deepscaler_b768_streaming_s2_${TS}}
mkdir -p "${RUN_ROOT}"
cat > "${RUN_ROOT}/trial_config.env" <<CFG
BATCH=768
NUM_STEPS=2
EXPECTED_SAMPLES=1536
ROLLOUT_N=8
TRAJECTORIES_PER_STEP=6144
MAX_CONCURRENCY=3840
DISPATCH_WORKERS=480
ORCHESTRA_VLLM_MAX_ACTIVE=2560
EDITOR_VLLM_MAX_ACTIVE=3584
SUB_AGENT_VLLM_MAX_ACTIVE=3584
ROLLOUT_MAX_NUM_SEQS=6144
PEER_MAX_NUM_SEQS=6400
SUB_AGENT_MAX_NUM_SEQS=6144
ROLLOUT_MAX_NUM_BATCHED_TOKENS=65536
PEER_MAX_NUM_BATCHED_TOKENS=131072
SUB_AGENT_MAX_NUM_BATCHED_TOKENS=98304
STREAM_CHAT=1
CHAT_RETRIES=3
STRUCTURED_RETRIES=3
RUN_ROOT=${RUN_ROOT}
CFG

exec env \
  DS_MAS_ROOT="${ROOT}" DS_VERL_ROOT="${ROOT}/verl" DS_ALL_GPUS=8,9,10,11,12,13,14,15 \
  DS_TIMESTAMP="${TS}" DS_RUN_DIR="${RUN_ROOT}/train" DS_LOG_DIR="${RUN_ROOT}/logs" \
  DS_TRAIN_BATCH_SIZE=768 DS_PPO_MINI_BATCH_SIZE=128 DS_PPO_MICRO_BATCH_SIZE_PER_GPU=2 \
  DS_LOG_PROB_MICRO_BATCH_SIZE_PER_GPU=4 DS_ROLLOUT_N=8 DS_EDITOR_GROUP_SIZE=8 \
  DS_MAX_PROMPT_LENGTH=15000 DS_MAX_RESPONSE_LENGTH=8192 DS_ROLLOUT_MAX_MODEL_LEN=23192 \
  DS_ROLLOUT_TP=8 DS_ROLLOUT_GPU_MEM_UTIL=0.85 DS_PEER_GPU_MEMORY_UTILIZATION=0.90 \
  DS_SUB_AGENT_GPU_MEMORY_UTILIZATION=0.90 \
  DS_ROLLOUT_MAX_NUM_SEQS=6144 DS_PEER_MAX_NUM_SEQS=6400 DS_SUB_AGENT_MAX_NUM_SEQS=6144 \
  DS_ROLLOUT_MAX_NUM_BATCHED_TOKENS=65536 DS_PEER_MAX_NUM_BATCHED_TOKENS=131072 \
  DS_SUB_AGENT_MAX_NUM_BATCHED_TOKENS=98304 \
  DS_MAX_CONCURRENCY=3840 DS_ORCHESTRA_VLLM_MAX_ACTIVE=2560 \
  DS_EDITOR_VLLM_MAX_ACTIVE=3584 DS_SUB_AGENT_VLLM_MAX_ACTIVE=3584 \
  DS_DISPATCH_WORKERS_PER_PROCESS=480 DS_REWARD_NUM_WORKERS=8 \
  DS_MAX_TRAIN_ROWS=1536 DS_DATA_VAL_RATIO=0 DS_DATA_PAD_TO_MULTIPLE=768 DS_TOTAL_EPOCHS=1 \
  DS_RUN_ORCHESTRA=1 DS_RUN_EDITOR=0 DS_NUM_INTERMEDIATE_CHECKPOINTS=0 DS_SAVE_FREQ=-1 \
  DS_STREAM_CHAT=1 DS_CHAT_RETRIES=3 DS_STRUCTURED_RETRIES=3 DS_HTTP_TIMEOUT=120 \
  bash "${ROOT}/verl/scripts/run_deepscaler_mas_loop_full.sh" "$@"
