#!/usr/bin/env bash
set -euo pipefail

# DeepScaleR-only MAS_Loop adapter. Every experiment-owned input is DS_* and is
# explicitly mapped once into the generic trainer namespace below.
ulimit -c 0
ulimit -n 1048576 2>/dev/null || true

DS_MAS_ROOT=${DS_MAS_ROOT:-/path/to/MAS_Loop}
DS_VERL_ROOT=${DS_VERL_ROOT:-${DS_MAS_ROOT}/verl}
DS_ALL_GPUS=${DS_ALL_GPUS:-8,9,10,11,12,13,14,15}
DS_TIMESTAMP=${DS_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}
DS_TASK_JSON=${DS_TASK_JSON:-${DS_MAS_ROOT}/datasets/DeepScaleR/deepscaler_train.json}
