@dataclass
class SFTWarmupConfig:
    """Configuration for SFT warm-up training."""

    model_name: str = "Qwen/Qwen2.5-7B-Instruct"
    output_dir: str = "checkpoints/sft_warmup"
    learning_rate: float = 2e-5
    num_epochs: int = 3
    batch_size: int = 4
    gradient_accumulation_steps: int = 4
    max_seq_length: int = 4096
    warmup_ratio: float = 0.1
    weight_decay: float = 0.01
    save_steps: int = 500
    eval_steps: int = 500
    logging_steps: int = 50
    # Data
    seed_data_path: str = "data/seed_mas_evo_traj.jsonl"
    train_split: float = 0.9
    # Training mode
    train_orchestra: bool = True
    train_editor: bool = True
    # Whether to use LoRA
    use_lora: bool = True
    lora_r: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05


class SFTWarmupTrainer:
    """SFT warm-up trainer for Orchestra and Editor models.

    Loads seed data from MAS-EvoTraj JSONL files and trains student models
    using supervised fine-tuning.

    The trainer handles both Orchestra training (task -> MAS JSON) and
    Editor training (task + trajectory -> patch JSON).
    """

    def __init__(self, config: SFTWarmupConfig):
        self.config = config
        self._dataset: Optional[EvoTrajDataset] = None

    def load_data(self) -> EvoTrajDataset:
        """Load seed data from the configured JSONL path."""
        self._dataset = EvoTrajDataset().load(self.config.seed_data_path)
        print(f"[SFTWarmup] loaded {len(self._dataset)} samples from {self.config.seed_data_path}")
        return self._dataset

    @property
    def dataset(self) -> EvoTrajDataset:
        if self._dataset is None:
            self.load_data()
        return self._dataset

    def build_orchestra_data(self) -> list[dict[str, Any]]:
        """Build Orchestra SFT training data: (task, constraints) -> source MAS JSON.

        Each sample maps:
            input: {"task_text": ..., "constraints": {...}}
            output: MAS config JSON
        """
        samples = []
        for s in self.dataset:
            if s.src_mas is None:
                continue
            samples.append({
                "input": {
                    "task_text": s.task.get("task_text", ""),
                    "constraints": s.edit_constraints,
                },
                "output": s.src_mas.to_dict(),
            })

        # Split into train/eval
        split = int(len(samples) * self.config.train_split)
        train_data = samples[:split]
        eval_data = samples[split:]
        print(f"[SFTWarmup] orchestra data: train={len(train_data)}, eval={len(eval_data)}")
        return train_data

    def build_editor_data(self) -> list[dict[str, Any]]:
        """Build Editor SFT training data: (task, src_mas, trajectory, constraints) -> patch.

        Each sample maps:
            input: {"task": ..., "src_mas": ..., "src_trajectory": ..., "constraints": ...}
            output: diagnosis + patch JSON
        """
        samples = []
        for s in self.dataset:
            if s.edit_operation is None or s.src_mas is None or s.src_trajectory is None:
                continue
            samples.append({
                "input": {
                    "task": s.task,
                    "src_mas": s.src_mas.to_dict(),
                    "src_trajectory": s.src_trajectory.to_dict(),
                    "constraints": s.edit_constraints,
                },
                "output": s.edit_operation.to_dict(),
            })

        split = int(len(samples) * self.config.train_split)
        train_data = samples[:split]
        eval_data = samples[split:]
        print(f"[SFTWarmup] editor data: train={len(train_data)}, eval={len(eval_data)}")
        return train_data

    def train(self) -> None:
        """Run SFT warm-up training for Orchestra and/or Editor.

        In a full implementation, this would use HuggingFace Trainer with:
        - AutoModelForCausalLM for text generation
        - AutoTokenizer with chat template
        - DataCollator for JSON formatting
        - Trainer with standard hyperparameters

        For now, this is a structural placeholder that loads data and
        validates the format, ready for integration with HuggingFace.
        """
        self.load_data()

        if self.config.train_orchestra:
            orch_data = self.build_orchestra_data()
            print(f"[SFTWarmup] Orchestra training: {len(orch_data)} samples ready")
            self._train_orchestra(orch_data)

        if self.config.train_editor:
            editor_data = self.build_editor_data()
            print(f"[SFTWarmup] Editor training: {len(editor_data)} samples ready")
            self._train_editor(editor_data)

